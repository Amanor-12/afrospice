    price: Number(spec.price || 0),
    unitCost:
      spec.unitCost === undefined ? estimateUnitCost(spec.price, spec.unitCostRatio) : Number(spec.unitCost),
    stock: Number(spec.stock ?? defaults.stock ?? 0),
    unitLabel: String(spec.unitLabel || defaults.unitLabel || "").trim(),
    casePack: Number(spec.casePack ?? defaults.casePack ?? 0),
    reorderPoint: Number(spec.reorderPoint ?? defaults.reorderPoint ?? 0),
    parLevel: Number(spec.parLevel ?? defaults.parLevel ?? 0),
    shelfLocation: String(spec.shelfLocation || "").trim(),
    receivingNotes: String(spec.receivingNotes || defaults.receivingNotes || "").trim(),
